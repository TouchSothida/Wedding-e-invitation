"""Inline the starter-kit SVG elements as JS strings: strips c2pa metadata and the per-file g-foil gradient (one shared definition lives in the page)."""
import re, json, sys
names = ['crest','wax-seal','butterfly','corner','divider','lotus']
out = {}
for n in names:
    s = open(f'svgsrc/{n}.svg').read()
    s = re.sub(r'<metadata>.*?</metadata>', '', s, flags=re.S)
    s = re.sub(r'\s+xmlns:c2pa="[^"]*"', '', s)
    s = re.sub(r'<defs><linearGradient id="g-foil".*?</linearGradient></defs>', '', s, count=1, flags=re.S)
    out[n] = s.strip()
js = '// generated by scripts/build_svg.py from the starter kit elements\nexport const SVG = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
js += '''export const FOIL_DEFS = `<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs><linearGradient id="g-foil" x1="0" y1="0" x2="1" y2=".35"><stop offset="0" stop-color="#9c7124"/><stop offset=".25" stop-color="#d9b15a"/><stop offset=".45" stop-color="#fbefc0"/><stop offset=".62" stop-color="#d9b15a"/><stop offset=".85" stop-color="#9c7124"/><stop offset="1" stop-color="#d9b15a"/></linearGradient></defs></svg>`;
export function corner(flipX, flipY) {
  const t = flipX && flipY ? 'translate(160 160) scale(-1 -1)' : flipX ? 'translate(160 0) scale(-1 1)' : flipY ? 'translate(0 160) scale(1 -1)' : '';
  return SVG.corner.replace('<g transform="">', `<g transform="${t}">`);
}
'''
open('js/svg.js','w').write(js)
print({k:len(v) for k,v in out.items()}, 'transform=""' in out['corner'] or '<g transform="">' in out['corner'])
